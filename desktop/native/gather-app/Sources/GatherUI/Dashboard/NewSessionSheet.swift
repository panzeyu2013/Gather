// Cut 4 / 4c-2i：自 DashboardView.swift 原样移出（新建工作区表单；原 720-960 行）。
// 行为/布局/文案不变：来源选择 + C1 四层预检 + 一跳建库入队。
import SwiftUI
import AppKit
import GatherProtocol

// MARK: - 新建工作区（来源选择 + C1 四层预检 + metadata.scan 一跳入队）

struct NewSessionSheet: View {
    @Bindable var viewModel: DashboardViewModel
    @Environment(\.dismiss) private var dismiss
    /// 4a-3b-2b：sheet 在 RootView 的 environment 树里。
    @Environment(\.languageStore) private var languageStore
    private var l10n: L10n { languageStore?.l10n ?? L10n(language: .zhCN) }
    /// 创建成功回调（TS createMutation onSuccess → navigate /sessions/:id）。
    let onCreated: (String) -> Void

    @State private var name = ""
    @State private var nameAutoFill = SessionNameAutoFill()
    @State private var folderPath = ""
    @State private var source = DashboardViewModel.SessionSource.local
    /// A5：选中目录被识别为 C1 Session（扫描根已重定向为 Capture）。
    @State private var isCaptureOneSession = false

    init(
        viewModel: DashboardViewModel,
        initialFolderPath: String = "",
        onCreated: @escaping (String) -> Void = { _ in }
    ) {
        self.viewModel = viewModel
        self.onCreated = onCreated
        // A5：新建工作区与菜单"导入文件夹"共用同一识别规则：C1 Session 只扫 Capture
        // （Trash 不导入）；会话名/显示位置仍用用户选中的 Session 名，不变成 "Capture"。
        let plan = initialFolderPath.isEmpty
            ? nil
            : C1SessionDirectoryResolver.importPlan(root: initialFolderPath)
        let displayRoot = plan?.layout.root ?? initialFolderPath
        let initialName = displayRoot.isEmpty
            ? ""
            : URL(fileURLWithPath: displayRoot).lastPathComponent
        _folderPath = State(initialValue: plan?.scanRoot ?? initialFolderPath)
        _isCaptureOneSession = State(initialValue: plan != nil)
        _name = State(initialValue: initialName)
        _nameAutoFill = State(initialValue: SessionNameAutoFill(lastAutoGeneratedName: initialName))
    }

    var body: some View {
        VStack(spacing: 0) {
            // 表单行交给 Form + .formStyle(.grouped) + LabeledContent：
            // 标签列、控件列、行内边距与选中高亮由系统负责。
            Form {
                nameSection
                sourceSection
                if let error = viewModel.createError {
                    // createError 是 CommandError（码/参数/诊断）：本地校验经
                    // .localized 上屏，API 诊断由 CommandErrorText 回退通用文案。
                    NativeBanner(text: CommandErrorText.resolve(error, with: l10n))
                }
            }
            .formStyle(.grouped)
            footer
        }
        .frame(width: 520)
        // N10：sheet 高度贴合内容。旧的固定 440pt 在 3 行表单下留出 200pt 以上
        // 空白；Capture One 来源会多出「连接预检」区块，因此按来源给两档高度。
        .frame(height: source == .captureOne ? 430 : 330)
        .task {
            // TS：对话框打开且来源为 Capture One 时自动预检。
            if source == .captureOne {
                await viewModel.runC1Preflight()
            }
        }
        .onChange(of: source) { _, newSource in
            let folderName = folderPath.isEmpty
                ? ""
                : URL(fileURLWithPath: folderPath).lastPathComponent
            if let updated = nameAutoFill.sourceChanged(
                toLocal: newSource == .local,
                currentName: name,
                folderName: folderName
            ) {
                name = updated
            }
            if newSource == .captureOne {
                Task { await viewModel.runC1Preflight() }
            }
        }
    }

    private var nameSection: some View {
        Section {
            LabeledContent(l10n("名称")) {
                TextField(
                    l10n("名称"),
                    text: nameBinding,
                    prompt: Text(source == .local
                        ? l10n("自动生成")
                        : l10n("默认用文件夹名"))
                )
                .labelsHidden()
            }
        } footer: {
            // N10：长提示从输入框 placeholder 移到分组脚注——placeholder 在标签列
            // 挤压下会被截断成「选择文件…」，而脚注有整行宽度。
            Text(source == .local
                ? l10n("选择文件夹后名称会自动生成，也可以先手动输入。")
                : l10n("留空则使用选中照片所在的文件夹名称。"))
        }
    }

    /// 名称输入绑定：用户真的改了文本才标记「已编辑」。
    ///
    /// 值没变就直接 return——TextField 会在焦点变化等时机把当前文本原样回写一次，
    /// 那次回写不是用户意图；旧实现无条件清标记，一次空回写就会让自动命名永久失效
    /// （之后再选目录，名称停在旧值）。程序化赋值（选择目录、切换来源）走的是
    /// `name` 本身，不经过这个 setter。
    private var nameBinding: Binding<String> {
        Binding(
            get: { name },
            set: { newValue in
                guard newValue != name else { return }
                name = newValue
                nameAutoFill.userEdited()
            }
        )
    }

    @ViewBuilder
    private var sourceSection: some View {
        Section {
            Picker(l10n("导入来源"), selection: $source) {
                ForEach(DashboardViewModel.SessionSource.allCases) { option in
                    Text(option.label(with: l10n)).tag(option)
                }
            }
            .pickerStyle(.segmented)
        }
        if source == .local {
            Section {
                folderRow
                captureOneSessionHint
            }
        } else {
            Section {
                c1PreflightRows
            } header: {
                Text(l10n("Capture One 连接预检"))
            }
        }
    }

    private var canCreate: Bool {
        switch source {
        case .local:
            return !name.trimmingCharacters(in: .whitespaces).isEmpty && !folderPath.isEmpty
        case .captureOne:
            // 名称可留空（回退文件夹名），但预检/创建进行中禁用。
            if viewModel.isC1PreflightChecking { return false }
            // 预检已判失败时不再放行：createSessionFromCaptureOne 会重跑预检并
            // 直接返回 nil，点「创建」只会没有反馈（静默失败）。
            if case .finished(let result) = viewModel.c1Preflight, !result.passed {
                return false
            }
            return true
        }
    }

    /// TS handleSelectFolder（selectDirectory + 未编辑时用目录名填充名称）。
    ///
    /// 第三轮审计 F：改用非阻塞 `begin()`。旧实现的 `runModal()` 在 sheet 内
    /// 再开嵌套 runloop，会卡住主线程并让工具栏/菜单在新工作区表单打开期间失去响应。
    private func chooseFolder() {
        let panel = NSOpenPanel()
        panel.canChooseDirectories = true
        panel.canChooseFiles = false
        panel.allowsMultipleSelection = false
        panel.message = l10n("请选择包含照片的文件夹")
        Task { @MainActor in
            let response = await panel.begin()
            guard response == .OK, let url = panel.url else { return }
            applyFolder(url)
        }
    }

    /// 选择 / 拖入目录后更新路径与自动名称。
    ///
    /// 只有「名称为空」或「名称仍是上一次自动生成值」时才覆盖；
    /// 用户手动改过名称就保留（P2-15：第二次选目录不再吞掉更新）。
    private func applyFolder(_ url: URL) {
        // A5：C1 Session → 只把 Capture 作为扫描/入库根（Trash 不导入、Selects 不重复扫）；
        // 命名仍用用户选中的 Session 目录名（不是 "Capture"）。
        let plan = C1SessionDirectoryResolver.importPlan(root: url.path)
        folderPath = plan?.scanRoot ?? url.path
        isCaptureOneSession = plan != nil
        if let suggestedName = nameAutoFill.apply(
            folderName: URL(fileURLWithPath: plan?.layout.root ?? url.path).lastPathComponent,
            currentName: name
        ) {
            name = suggestedName
        }
    }

    private var folderRow: some View {
        LabeledContent(l10n("文件夹位置")) {
            HStack(spacing: GatherMetrics.Space.s) {
                folderValue
                Button(l10n("选择…"), action: chooseFolder)
                    .gatherButton(.secondary, size: .small)
                    .help(l10n("请选择包含照片的文件夹"))
                    .accessibilityLabel(l10n("请选择包含照片的文件夹"))
            }
        }
        .dropDestination(for: URL.self) { urls, _ in
            guard let url = urls.first(where: { isDirectoryURL($0) }) else { return false }
            applyFolder(url)
            return true
        }
    }

    /// A5：识别结果可见（不只写注释）：C1 Session 只索引 Capture。
    @ViewBuilder
    private var captureOneSessionHint: some View {
        if isCaptureOneSession {
            HStack(spacing: GatherMetrics.Space.xs) {
                Image(systemName: "folder.badge.gearshape")
                    .font(GatherFont.secondary)
                    .foregroundStyle(GatherTheme.secondaryText)
                    .accessibilityHidden(true)
                Text(l10n("已识别 Capture One Session：只索引 Capture（Trash/Selects 不导入）"))
                    .font(GatherFont.secondary)
                    .foregroundStyle(.secondary)
                    .fixedSize(horizontal: false, vertical: true)
            }
        }
    }

    /// 只读路径展示。不要用 disabled TextField 的 prompt 当占位：
    /// prompt 会与按钮标题同时出现（截图里的两个「选择文件夹」）。
    @ViewBuilder
    private var folderValue: some View {
        HStack(spacing: GatherMetrics.Space.controlGap) {
            Image(systemName: "folder")
                .foregroundStyle(folderPath.isEmpty ? Color.secondary : GatherTheme.accent)
                .accessibilityHidden(true)
            if folderPath.isEmpty {
                Text(l10n("未选择文件夹"))
                    .foregroundStyle(.secondary)
            } else {
                Text(folderPath)
                    .foregroundStyle(.secondary)
                    .lineLimit(1)
                    .truncationMode(.middle)
                    .textSelection(.enabled)
                    .help(folderPath)
            }
        }
        .frame(maxWidth: .infinity, alignment: .leading)
    }

    /// TS Dialog c1Preflight 区块：检查清单 + 通过/引导文案。
    /// 状态行 = Label + SF Symbol + 语义色（不再用裸 ✓/✗ 字形与纯颜色信号）。
    @ViewBuilder
    private var c1PreflightRows: some View {
        switch viewModel.c1Preflight {
        case .idle:
            EmptyView()
        case .checking:
            HStack(spacing: GatherMetrics.Space.s) {
                ProgressView()
                    .controlSize(.small)
                Text(l10n("正在检查 Capture One 连接…"))
                    .font(GatherFont.secondary)
                    .foregroundStyle(.secondary)
            }
        case .finished(let result):
            ForEach(result.checks) { check in
                Label(
                    check.label.resolve(with: l10n),
                    systemImage: check.passed ? "checkmark.circle.fill" : "xmark.circle.fill"
                )
                .font(GatherFont.secondary)
                .foregroundStyle(check.passed ? GatherTheme.success : GatherTheme.error)
            }
            if result.passed {
                Text(l10n("预检通过：导入时读取 Capture One 当前选中的照片。"))
                    .font(.footnote)
                    .foregroundStyle(.secondary)
            } else if let guidance = result.guidance {
                // 旧版 c1-preflight.ts：预检失败引导为 error 语义提示条。
                NativeBanner(text: guidance.resolve(with: l10n))
            }
        }
    }

    private var footer: some View {
        VStack(alignment: .leading, spacing: GatherMetrics.Space.m) {
            Text(footerHint)
                .font(.footnote)
                .foregroundStyle(.secondary)
                .fixedSize(horizontal: false, vertical: true)
            HStack(spacing: GatherMetrics.Space.s) {
                Spacer()
                // 创建途中不给取消出口：create() 起的是游离 Task，关掉 sheet 不会
                // 取消它，建库成功后会照样 onCreated 跳转——用户会「取消后仍被带走」。
                Button(l10n("取消")) { dismiss() }
                    .gatherButton(.secondary)
                    .keyboardShortcut(.cancelAction)
                    .disabled(viewModel.isCreating)
                Button(l10n("创建"), action: create)
                    .gatherButton(.primary)
                    .keyboardShortcut(.defaultAction)
                    .disabled(!canCreate || viewModel.isCreating)
            }
        }
        .padding(GatherMetrics.Space.l)
    }

    /// 禁用「创建」时把缺什么直接写在脚注里（P2-16）。
    private var footerHint: String {
        if source == .captureOne, viewModel.isC1PreflightChecking {
            return l10n("正在检查 Capture One 连接…")
        }
        if source == .captureOne,
           case .finished(let result) = viewModel.c1Preflight,
           !result.passed {
            return l10n("Capture One 预检未通过，请按上方提示处理后再创建。")
        }
        if source == .local {
            if folderPath.isEmpty {
                return l10n("请选择包含照片的文件夹")
            }
            if name.trimmingCharacters(in: .whitespaces).isEmpty {
                return l10n("请填写工作区名称")
            }
        }
        return l10n("创建后会立即启动照片索引；索引进度和失败重试可在任务中心查看。")
    }

    /// TS handleCreate：本地 → createFromDirectory；Capture One → 预检门控后
    /// 读选中照片建库（未选中报“请先在 Capture One 中选择照片”）。
    private func create() {
        // 4b-2e：动作发生时按当前界面语言解析（toast / 默认会话名），VM 不读全局。
        let l10n = self.l10n
        Task {
            let session: SessionData?
            switch source {
            case .local:
                session = await viewModel.createSession(
                    name: name.trimmingCharacters(in: .whitespaces),
                    sourcePath: folderPath,
                    with: l10n
                )
            case .captureOne:
                session = await viewModel.createSessionFromCaptureOne(
                    name: name.trimmingCharacters(in: .whitespaces),
                    with: l10n
                )
            }
            if let session {
                dismiss()
                // TS createMutation onSuccess L220：创建成功后立即跳转
                // /sessions/:id（控制中心）；toast 已由 ViewModel 展示。
                onCreated(session.id)
            }
        }
    }
}

/// 新建工作区名称的自动填充状态机（纯值类型，便于回归测试）。
///
/// 不变量（三条，其余都由它们推出）：
/// 1. **名称为空 ⇒ 允许自动填充**——没有可覆盖的内容，用户清空就是想重新自动；
/// 2. **用户手改过的非空名称永不被自动覆盖**，哪怕改回与自动名逐字相同；
/// 3. **名称仍是上一次自动值且用户没动过 ⇒ 再次选目录 / 切来源时跟随目录名更新**。
///
/// 「有没有手改过」用独立布尔 hasUserEdited 记，而不是把 lastAutoGeneratedName 清空
/// 冒充：一旦混用，任何一次「未改变文本的回写」（TextField 在焦点变化时会把同样的
/// 值 set 回来）都会被当成编辑，自动命名永久失效；反过来，用户手改后清空名称也
/// 无法与「从没自动过」区分。
struct SessionNameAutoFill: Equatable {
    /// 上一次由目录名自动生成的名称；空串表示当前没有可追踪的自动值。
    private(set) var lastAutoGeneratedName: String

    /// 用户是否亲手改过名称输入框。
    private(set) var hasUserEdited: Bool

    init(lastAutoGeneratedName: String = "", hasUserEdited: Bool = false) {
        self.lastAutoGeneratedName = lastAutoGeneratedName
        self.hasUserEdited = hasUserEdited
    }

    /// 用户真的改了输入框（调用方需先过滤「值没变」的回写）。
    mutating func userEdited() {
        hasUserEdited = true
    }

    /// 选目录 / 拖入目录：返回应写回输入框的名称；nil = 保留用户当前输入。
    mutating func apply(folderName: String, currentName: String) -> String? {
        guard !folderName.isEmpty else { return nil }
        let trimmed = currentName.trimmingCharacters(in: .whitespaces)
        if !trimmed.isEmpty {
            guard !hasUserEdited, currentName == lastAutoGeneratedName else { return nil }
        }
        lastAutoGeneratedName = folderName
        // 自动值重新接管，后续换目录应当继续跟随。
        hasUserEdited = false
        return folderName
    }

    /// 来源切换：切离本地清掉自动名（用户手写的名字保留），切回本地在名称为空时
    /// 从目录名恢复。返回应写回的名称；nil = 保留用户当前输入。
    mutating func sourceChanged(
        toLocal: Bool,
        currentName: String,
        folderName: String
    ) -> String? {
        let trimmed = currentName.trimmingCharacters(in: .whitespaces)
        if toLocal {
            guard trimmed.isEmpty, !folderName.isEmpty else { return nil }
            lastAutoGeneratedName = folderName
            hasUserEdited = false
            return folderName
        }
        guard trimmed.isEmpty || (!hasUserEdited && currentName == lastAutoGeneratedName) else {
            return nil
        }
        lastAutoGeneratedName = ""
        hasUserEdited = false
        return ""
    }
}
